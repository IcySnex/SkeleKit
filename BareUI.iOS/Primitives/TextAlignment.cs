namespace BareUI;

/// <summary>
/// Horizontal alignment of text within a control.
/// </summary>
public enum TextAlignment
{
	/// <summary>
	/// Aligned to the leading (left) edge.
	/// </summary>
	Leading,

	/// <summary>
	/// Centered.
	/// </summary>
	Center,

	/// <summary>
	/// Aligned to the trailing (right) edge.
	/// </summary>
	Trailing
}
