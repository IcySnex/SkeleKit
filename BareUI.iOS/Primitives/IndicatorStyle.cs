namespace BareUI;

/// <summary>
/// The color of a scroll view's indicator bar.
/// </summary>
public enum IndicatorStyle
{
	/// <summary>
	/// Follows the system appearance.
	/// </summary>
	Default,

	/// <summary>
	/// A dark bar, for light content.
	/// </summary>
	Dark,

	/// <summary>
	/// A light bar, for dark content.
	/// </summary>
	Light
}
