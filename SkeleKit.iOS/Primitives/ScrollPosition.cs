namespace SkeleKit;

/// <summary>
/// Where a scrolled-to item lands in the viewport.
/// </summary>
public enum ScrollPosition
{
	/// <summary>
	/// At the top (or leading edge of a carousel).
	/// </summary>
	Top,

	/// <summary>
	/// Centered.
	/// </summary>
	Center,

	/// <summary>
	/// At the bottom (or trailing edge of a carousel).
	/// </summary>
	Bottom
}
