namespace SkeleKit;

/// <summary>
/// The color scheme of the keyboard raised by a text input.
/// </summary>
public enum KeyboardLook
{
	/// <summary>
	/// Follows the system appearance.
	/// </summary>
	Default,

	/// <summary>
	/// Always light, whatever the system appearance.
	/// </summary>
	Light,

	/// <summary>
	/// Always dark, whatever the system appearance.
	/// </summary>
	Dark
}
