namespace SkeleKit;

/// <summary>
/// The app's light or dark appearance.
/// </summary>
public enum Appearance
{
	/// <summary>
	/// Follows the system setting.
	/// </summary>
	System,

	/// <summary>
	/// Always uses the light appearance.
	/// </summary>
	Light,

	/// <summary>
	/// Always uses the dark appearance.
	/// </summary>
	Dark
}
